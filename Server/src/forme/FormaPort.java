    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int port;
        try {
            port = Integer.parseInt(jTextField1.getText());
        } catch (NumberFormatException numberFormatException) {
            JOptionPane.showMessageDialog(this, "Грешка, порт мора да буде број! Измене нису сачуване.", "ГРЕШКА", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if(port >= 0 && port <= 65535)
        {
            try {
                konfiguracija.Konfiguracija.getInstance().setProperty("port", String.valueOf(port));
                konfiguracija.Konfiguracija.getInstance().sacuvajIzmene();
                JOptionPane.showMessageDialog(this, "Измене су сачуване!", "УСПЕХ", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
            } catch (IOException ex) {
                System.getLogger(FormaPort.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Грешка, порт није у добром опсегу! Измене нису сачуване.", "ГРЕШКА", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

